import path from 'node:path';
import { chromium } from 'playwright';
const BASE = 'http://localhost:8002';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1280, height: 1250 } });
await page.goto(BASE, { waitUntil: 'networkidle' });
const justMe = page.getByRole('button', { name: 'Just me (no login)' });
if (await justMe.isVisible()) await justMe.click();
await page.waitForSelector('text=TridentSlicer');
await page.locator('input[type="file"][accept*=".stl"]').setInputFiles(path.resolve('fixtures/test-cube.stl'));
await page.waitForSelector('text=Ready to slice', { timeout: 15000 });
const panel = page.locator('.panel-settings');
await panel.getByRole('button', { name: 'Resin', exact: true }).click();
await panel.getByLabel('Printer vendor').selectOption({ label: 'UniFormation' });
await panel.getByLabel('Printer', { exact: true }).selectOption({ label: 'GKtwo' });
await page.waitForTimeout(800);
await panel.getByLabel('Resin vendor').selectOption({ index: 1 });
await page.waitForTimeout(600);
await panel.screenshot({ path: '/work/mock-before.png' });
console.log(await panel.innerText());
await b.close();
